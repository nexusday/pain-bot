const COMPILADAS = [...FRASES]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([es, en, pt]) => ({
    re: new RegExp(`(?<![\\p{L}\\p{N}])${es.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\p{L}\\p{N}])`, 'giu'),
    en,
    pt,
  }))

function capitalizarComo(original, traduccion) {
  if (!traduccion || !original) return traduccion
  const letra = original[0]
  if (letra === letra.toUpperCase() && letra !== letra.toLowerCase()) {
    return traduccion.charAt(0).toUpperCase() + traduccion.slice(1)
  }
  if (letra === letra.toLowerCase() && letra !== letra.toUpperCase()) {
    return traduccion.charAt(0).toLowerCase() + traduccion.slice(1)
  }
  return traduccion
}

export function localizarTexto(lang, texto) {
  if (!texto || typeof texto !== 'string' || lang === 'es' || (lang !== 'en' && lang !== 'pt')) return texto
  const clave = lang === 'pt' ? 'pt' : 'en'
  let salida = texto
  for (const frase of COMPILADAS) {
    salida = salida.replace(frase.re, (coincidencia) => capitalizarComo(coincidencia, frase[clave]))
  }
  return salida
}

