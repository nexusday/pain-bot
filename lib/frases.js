const COMPILADAS = [...FRASES]
  .sort((a, b) => b[0].length - a[0].length)
  .map(([es, en, pt]) => ({
    re: new RegExp(`(?<![\\p{L}\\p{N}])${es.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?![\\p{L}\\p{N}])`, 'giu'),
    en,
    pt,
  }))

function capitalizarComo(original, traduccion) {
  if (!traduccion || !original) return traduccion
  const letra = original[0]
  if (letra === letra.toUpperCase() && letra !== letra.toLowerCase()) {
    return traduccion.charAt(0).toUpperCase() + traduccion.slice(1)
  }
  if (letra === letra.toLowerCase() && letra !== letra.toUpperCase()) {
    return traduccion.charAt(0).toLowerCase() + traduccion.slice(1)
  }
  return traduccion
}

function normalizarTipografia(texto) {
  let salida = ''
  for (const ch of texto) {
    const cp = ch.codePointAt(0)
    const rangos = [
      [0x1D400, 0x1D419, 65],
      [0x1D41A, 0x1D433, 97],
      [0x1D434, 0x1D44D, 65],
      [0x1D44E, 0x1D467, 97],
      [0x1D468, 0x1D481, 65],
      [0x1D482, 0x1D49B, 97],
      [0x1D5A0, 0x1D5B9, 65],
      [0x1D5BA, 0x1D5D3, 97],
      [0x1D5D4, 0x1D5ED, 65],
      [0x1D5EE, 0x1D607, 97],
      [0x1D608, 0x1D621, 65],
      [0x1D622, 0x1D63B, 97],
      [0x1D63C, 0x1D655, 65],
      [0x1D656, 0x1D66F, 97],
      [0x1D670, 0x1D689, 65],
      [0x1D68A, 0x1D6A3, 97],
    ]
    let plano = null
    for (const [desde, hasta, base] of rangos) {
      if (cp >= desde && cp <= hasta) {
        plano = String.fromCharCode(base + (cp - desde))
        break
      }
    }
    if (!plano && cp >= 0xFF21 && cp <= 0xFF3A) plano = String.fromCharCode(65 + cp - 0xFF21)
    if (!plano && cp >= 0xFF41 && cp <= 0xFF5A) plano = String.fromCharCode(97 + cp - 0xFF41)
    salida += plano || ch
  }
  return salida
}

export function localizarTexto(lang, texto) {
  if (!texto || typeof texto !== 'string' || lang === 'es' || (lang !== 'en' && lang !== 'pt')) return texto
  const clave = lang === 'pt' ? 'pt' : 'en'
  let salida = normalizarTipografia(texto)
  for (const frase of COMPILADAS) {
    salida = salida.replace(frase.re, (coincidencia) => capitalizarComo(coincidencia, frase[clave]))
  }
  return salida.replace(/[¿¡]/g, '')
}

function proteger(texto, transformar) {
  const guardados = []
  const base = texto.replace(/(https?:\/\/\S+|@[0-9]{6,})/g, (trozo) => {
    const marca = `\uE000${guardados.length}\uE001`
    guardados.push(trozo)
    return marca
  })
  const salida = transformar(base)
  return salida.replace(/\uE000(\d+)\uE001/g, (_, indice) => guardados[Number(indice)])
}

export function localizarSalida(conn, texto) {
  if (typeof texto !== 'string' || !texto) return texto
  const lang = idiomaDe(conn)
  if (lang === 'es') return texto
  return proteger(texto, (libre) => localizarTexto(lang, libre))
}

const CAMPOS = new Set(['text', 'caption', 'footer', 'title', 'body', 'description', 'buttonText', 'header'])
const SALTAR = new Set(['contextInfo', 'mentionedJid', 'quoted', 'edit', 'jpegThumbnail', 'url', 'id', 'rowId'])

function esBinario(valor) {
  return Buffer.isBuffer(valor) || valor instanceof Uint8Array
}

export function localizarContenido(conn, contenido) {
  if (idiomaDe(conn) === 'es' || contenido == null) return contenido
  if (typeof contenido === 'string') return localizarSalida(conn, contenido)
  if (typeof contenido !== 'object' || esBinario(contenido)) return contenido
  if (Array.isArray(contenido)) return contenido.map((item) => localizarContenido(conn, item))

  const copia = { ...contenido }
  for (const clave of Object.keys(copia)) {
    if (SALTAR.has(clave) || esBinario(copia[clave])) continue
    if (CAMPOS.has(clave) && typeof copia[clave] === 'string') {
      copia[clave] = localizarSalida(conn, copia[clave])
    } else if (copia[clave] && typeof copia[clave] === 'object') {
      copia[clave] = localizarContenido(conn, copia[clave])
    }
  }
  return copia
}
